MARKER_PREFIX = "# Generated by supagents from "
MARKER_SUFFIX = ". Do not edit; edit the source instead."


@dataclass(slots=True)
class Plan:
    """A single (source x target) emission plan."""

    source: Source
    target_name: str
    target: TargetConfig
    output_path: Path
    rendered: str


@dataclass(slots=True)
class BuildSummary:
    """Aggregated results from a build or check run."""

    sources: list[Source] = field(default_factory=list)
    plans: list[Plan] = field(default_factory=list)
    written: list[Path] = field(default_factory=list)
    skipped_unchanged: list[Path] = field(default_factory=list)
    orphans: list[Path] = field(default_factory=list)
    fatal_errors: list[tuple[Path, str]] = field(default_factory=list)

    @property
    def error_count(self) -> int:
        return sum(len(s.errors) for s in self.sources)

    @property
    def warning_count(self) -> int:
        return sum(len(s.warnings) for s in self.sources)


@dataclass(slots=True)
class CleanPlan:
    """Aggregated orphan scan and causal diagnostics for ``clean``."""

    orphans: list[Path] = field(default_factory=list)
    sources: list[Source] = field(default_factory=list)
    fatal_errors: list[tuple[Path, str]] = field(default_factory=list)

    @property
    def has_blockers(self) -> bool:
        return bool(self.fatal_errors) or any(s.errors or s.warnings for s in self.sources)


def marker_line(rel_path: Path) -> str:
    """The marker comment placed on the first line inside the frontmatter."""
    return f"{MARKER_PREFIX}{rel_path.as_posix()}{MARKER_SUFFIX}"


def _is_marker(line: str) -> bool:
    return line.startswith(MARKER_PREFIX) and line.endswith(MARKER_SUFFIX)


def has_marker(text: str) -> bool:
    """True if ``text``'s frontmatter contains the supagents marker comment.

    Tolerates reformatting that moves the marker elsewhere within the
    frontmatter block (e.g. another tool sorting YAML keys).
    """
    lines = text.splitlines()
    if not lines:
        return False
    if _is_marker(lines[0]):
        return True
    if lines[0].rstrip() != "---":
        return False
    for line in lines[1:]:
        if line.rstrip() == "---":
            return False
        if _is_marker(line):
            return True
    return False


def render(
    rel_path: Path, frontmatter: CommentedMap, body: str, target: TargetConfig | None = None
) -> str:
    """Produce the full file contents for one output."""
    if target is not None and target.format == "toml":
        if target.body_key in frontmatter:
            raise ParseError(f"{target.body_key!r} is reserved for the source body")
        try:
            data = dict(frontmatter)
            data[target.body_key] = body.rstrip("\n") + "\n"
            content = marker_line(rel_path) + "\n" + tomli_w.dumps(data, multiline_strings=True)
        except (TypeError, ValueError, RecursionError) as e:
            raise ParseError(f"frontmatter cannot be represented as TOML: {e}") from e
    else:
        fm_text = dump_yaml(frontmatter) if frontmatter else ""
        content = f"---\n{marker_line(rel_path)}\n{fm_text}---\n\n{body.rstrip('\n')}\n"
    try:
        content.encode("utf-8")
    except UnicodeError as e:
        raise ParseError(f"output cannot be encoded as UTF-8: {e}") from e
    return content


def resolve_output_path(
    source: Source,
    target: TargetConfig,
    scope: Scope,
    cwd: Path,
    output_directive: str | None,
) -> Path:
    """Where the rendered file for ``target`` should land."""
    if output_directive is not None:
        p = Path(output_directive).expanduser()
        if not p.is_absolute():
            p = source.path.parent / p
        return p
    return output_dir(target, scope, cwd) / f"{source.name}{target.filename_suffix}"


def _effective_source_dir(scope: Scope, cwd: Path, source_dir: Path | None) -> Path:
    return source_dir if source_dir is not None else source_root(scope, cwd)


def output_diff(path: Path, content: str) -> str:
    """Preview an addition, edit, or removal without changing the filesystem."""
    exists = path.exists()
    previous = path.read_text(encoding="utf-8") if exists else ""
    lines = unified_diff(
        previous.splitlines(keepends=True),
        content.splitlines(keepends=True),
        fromfile=str(path) if exists else "/dev/null",
        tofile=str(path) if content else "/dev/null",
    )
    return "".join(
        line if line.endswith("\n") else line + "\n\\ No newline at end of file\n" for line in lines
    )


def atomic_write(path: Path, content: str, *, skip_if_unchanged: bool = True) -> bool:
    """Write ``content`` to ``path`` atomically with fsync. Return True if changed."""
    if skip_if_unchanged and path.is_file():
        try:
            if path.read_text(encoding="utf-8") == content:
                return False
        except (OSError, UnicodeError):
            pass
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=path.parent, delete=False
        ) as tf:
            tmp = Path(tf.name)
            tf.write(content)
            tf.flush()
            os.fsync(tf.fileno())
        # NamedTemporaryFile creates files at 0600; honor the user's umask instead
        # so generated dotfiles get the conventional 0644 (or whatever umask yields).
        umask = os.umask(0)
        try:
            tmp.chmod(0o666 & ~umask)
        finally:
            os.umask(umask)
        tmp.replace(path)
    except BaseException:
        if tmp is not None:
            tmp.unlink(missing_ok=True)
        raise
    return True


def _append_unique(items: list[str], message: str) -> None:
    if message not in items:
        items.append(message)


def plan_source(
    source: Source,
    config: Config,
    scope: Scope,
    cwd: Path,
    targets: set[str] | None = None,
) -> list[Plan]:
    """Compute every ``Plan`` (source x target) that would be emitted."""
    plans: list[Plan] = []
    scope_root = cwd if scope == "project" else Path.home()
    scope_root_resolved = scope_root.resolve()
    for tname, block in source.targets.items():
        if targets is not None and tname not in targets:
            continue
        target = config.targets[tname]
        try:
            out_path = resolve_output_path(source, target, scope, cwd, block.output)
            resolved = out_path.resolve()
        except (OSError, ValueError, RuntimeError) as e:
            _append_unique(source.errors, f"{tname}: invalid output path: {e}")
            continue
        if block.output is not None:
            try:
                resolved.relative_to(scope_root_resolved)
            except ValueError:
                _append_unique(
                    source.warnings,
                    f"target {tname!r} OUTPUT {block.output!r} resolves outside "
                    f"{scope_root} ({out_path}); verify this is intentional",
                )
        fm = compute_frontmatter(source.shared_frontmatter, block.frontmatter)
        body = compute_body(source.body, block.append_body)
        if tname == "CODEX" and any(
            not isinstance(fm.get(key), str) or not fm[key].strip()
            for key in ("name", "description")
        ):
            _append_unique(source.errors, "CODEX requires non-empty name and description strings")
            continue
        try:
            rendered = render(source.rel_path, fm, body, target)
        except ParseError as e:
            _append_unique(source.errors, f"{tname}: {e}")
            continue
        plans.append(
            Plan(
                source=source,
                target_name=tname,
                target=target,
                output_path=out_path,
                rendered=rendered,
            )
        )
    return plans


def _validate_plans(summary: BuildSummary, inputs: set[Path]) -> dict[Path, str]:
    outputs: set[Path] = set()
    existing: dict[Path, str] = {}
    for plan in summary.plans:
        path = plan.output_path
        resolved = path.resolve()
        problem: str | None = None
        if resolved in inputs:
            problem = "output would overwrite a source"
        elif resolved in outputs:
            problem = "multiple outputs resolve to the same path"
        else:
            try:
                is_symlink = path.is_symlink()
                exists = path.exists() if not is_symlink else False
                is_file = path.is_file() if exists else False
            except OSError as e:
                problem = f"cannot inspect existing output: {e}"
            else:
                if is_symlink:
                    problem = "refusing to replace a symlink"
                elif exists and not is_file:
                    problem = "existing output is not a regular file"
                elif exists:
                    try:
                        content = path.read_text(encoding="utf-8")
                    except (OSError, UnicodeError):
                        problem = "existing output is not a readable UTF-8 file"
                    else:
                        if not has_marker(content):
                            problem = "refusing to overwrite a file not generated by supagents"
                        else:
                            existing[path] = content
        outputs.add(resolved)
        if problem:
            summary.fatal_errors.append((path, problem))
    return existing


def _build_with_partials(
    scope: Scope,
    config: Config,
    cwd: Path,
    *,
    dry_run: bool,
    targets: set[str] | None,
    source_dir: Path | None,
    strict: bool,
) -> tuple[BuildSummary, list[Path]]:
    summary = BuildSummary()
    summary.sources, partial_paths, summary.fatal_errors = collect_sources(
        scope, config, cwd, source_dir
    )

    for src in summary.sources:
        summary.plans.extend(plan_source(src, config, scope, cwd, targets))
    # Validate the complete plan before changing anything. A marker establishes
    # generator ownership, not a security boundary against a concurrent writer.
    inputs = {src.path.resolve() for src in summary.sources}
    if not summary.fatal_errors:
        inputs.update(p.resolve() for p in partial_paths)
    existing = _validate_plans(summary, inputs)
    if summary.fatal_errors or summary.error_count or (strict and summary.warning_count):
        return summary, partial_paths
    for plan in summary.plans:
        if existing.get(plan.output_path) == plan.rendered:
            summary.skipped_unchanged.append(plan.output_path)
            continue
        if dry_run:
            summary.written.append(plan.output_path)
            continue
        try:
            atomic_write(plan.output_path, plan.rendered, skip_if_unchanged=False)
        except OSError as e:
            summary.fatal_errors.append((plan.output_path, f"write failed: {e}"))
            break
        summary.written.append(plan.output_path)
    return summary, partial_paths


def build(
    scope: Scope,
    config: Config | None = None,
    cwd: Path | None = None,
    dry_run: bool = False,
    targets: set[str] | None = None,
    source_dir: Path | None = None,
    strict: bool = False,
) -> BuildSummary:
    """Run the build for all sources in ``scope``.

    In dry-run mode, ``written`` and ``skipped_unchanged`` still reflect what
    *would* change so callers can detect drift without touching the filesystem.
    """
    resolved_config = config or Config.load()
    resolved_cwd = cwd or Path.cwd()
    summary, _ = _build_with_partials(
        scope,
        resolved_config,
        resolved_cwd,
        dry_run=dry_run,
        targets=targets,
        source_dir=source_dir,
        strict=strict,
    )
    return summary


def _scan_orphans(
    sources: list[Source],
    partial_paths: list[Path],
    scope: Scope,
    config: Config,
    cwd: Path,
    targets: set[str] | None,
) -> list[Path]:
    # Different targets may share a directory. A target filter narrows scanning,
    # but must never classify another target's current output as obsolete.
    expected: set[Path] = set()
    for src in sources:
        for name, block in src.targets.items():
            try:
                expected.add(
                    resolve_output_path(
                        src, config.targets[name], scope, cwd, block.output
                    ).resolve()
                )
            except (OSError, ValueError, RuntimeError) as e:
                raise ParseError(f"{src.path}: {name}: invalid output path: {e}") from e
    # A migrated profile may retain a generated marker. Overlapping output
    # directories must never turn a canonical source or partial into a cleanup candidate.
    expected.update(src.path.resolve() for src in sources)
    expected.update(p.resolve() for p in partial_paths)

    orphans: dict[Path, Path] = {}
    for tname, target in config.targets.items():
        if targets is not None and tname not in targets:
            continue
        out_dir = output_dir(target, scope, cwd)
        try:
            candidates = sorted(out_dir.iterdir())
        except FileNotFoundError:
            if out_dir.is_symlink():
                raise
            continue
        for candidate in candidates:
            if not candidate.name.endswith(target.filename_suffix) or candidate.is_symlink():
                continue
            if not stat.S_ISREG(candidate.stat().st_mode):
                continue
            try:
                content = candidate.read_text(encoding="utf-8")
            except UnicodeError:
                # Binary files cannot contain a valid generated text header.
                continue
            resolved_candidate = candidate.resolve()
            if has_marker(content) and resolved_candidate not in expected:
                orphans.setdefault(resolved_candidate, candidate)
    return sorted(orphans.values())


def check(
    scope: Scope,
    config: Config | None = None,
    cwd: Path | None = None,
    targets: set[str] | None = None,
    source_dir: Path | None = None,
) -> BuildSummary:
    """Check expected outputs and configured directories for drift without writes.

    Require existing sources so a missing checkout never passes a CI gate.
    Orphan discovery is limited to the current configured output directories.
    """
    resolved_config = config or Config.load()
    resolved_cwd = cwd or Path.cwd()
    effective_source_dir = _effective_source_dir(scope, resolved_cwd, source_dir)
    summary, partial_paths = _build_with_partials(
        scope,
        resolved_config,
        resolved_cwd,
        dry_run=True,
        targets=targets,
        source_dir=effective_source_dir,
        strict=False,
    )
    if summary.fatal_errors or summary.error_count:
        return summary
    # Ambiguous sources cannot establish which outputs are obsolete. Ordinary
    # checks report warnings; strict checks reject them at the CLI boundary.
    if not summary.warning_count:
        try:
            summary.orphans = _scan_orphans(
                summary.sources,
                partial_paths,
                scope,
                resolved_config,
                resolved_cwd,
                targets,
            )
        except (ParseError, OSError, ValueError, RuntimeError) as e:
            summary.fatal_errors.append((effective_source_dir, str(e)))
    return summary


def plan_clean(
    scope: Scope,
    config: Config | None = None,
    cwd: Path | None = None,
    targets: set[str] | None = None,
    source_dir: Path | None = None,
) -> CleanPlan:
    """Collect orphaned outputs along with any source/partial diagnostics blocking cleanup."""
    resolved_config = config or Config.load()
    resolved_cwd = cwd or Path.cwd()
    effective_source_dir = _effective_source_dir(scope, resolved_cwd, source_dir)
    sources, partial_paths, fatal_errors = collect_sources(
        scope, resolved_config, resolved_cwd, effective_source_dir
    )
    if fatal_errors:
        return CleanPlan(sources=sources, fatal_errors=fatal_errors)
    for src in sources:
        plan_source(src, resolved_config, scope, resolved_cwd, targets)
    if any(src.errors or src.warnings for src in sources):
        return CleanPlan(sources=sources)
    try:
        orphans = _scan_orphans(
            sources, partial_paths, scope, resolved_config, resolved_cwd, targets
        )
    except (ParseError, OSError, ValueError, RuntimeError) as e:
        return CleanPlan(sources=sources, fatal_errors=[(effective_source_dir, str(e))])
    return CleanPlan(orphans=orphans, sources=sources)


def find_orphans(
    scope: Scope,
    config: Config | None = None,
    cwd: Path | None = None,
    targets: set[str] | None = None,
    source_dir: Path | None = None,
) -> list[Path]:
    """Marker-bearing output files for which no source still produces an output."""
    plan = plan_clean(scope, config=config, cwd=cwd, targets=targets, source_dir=source_dir)
    if plan.fatal_errors:
        details = "; ".join(f"{path}: {msg}" for path, msg in plan.fatal_errors)
        raise ParseError(f"cannot clean while sources are unreadable or invalid: {details}")
    if plan.has_blockers:
        issues = [
            f"{src.path}: {msg}" for src in plan.sources for msg in (*src.errors, *src.warnings)
        ]
        raise ParseError(f"cannot clean while sources have errors or warnings: {'; '.join(issues)}")
    return plan.orphans
